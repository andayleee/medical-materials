ALTER TABLE inventory_documents ADD COLUMN record_version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE suppliers ADD COLUMN record_version BIGINT NOT NULL DEFAULT 0;
CREATE TABLE inventory_events (
    id_inventory_events BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_documents_id BIGINT NOT NULL REFERENCES inventory_documents(id_inventory_documents),
    users_id BIGINT NOT NULL REFERENCES users(id_users),
    action VARCHAR(32) NOT NULL CHECK (action IN ('POSTED')),
    created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX inventory_events_document_idx ON inventory_events(inventory_documents_id);
CREATE INDEX inventory_events_users_idx ON inventory_events(users_id);
CREATE INDEX inventory_documents_status_idx ON inventory_documents(status);
