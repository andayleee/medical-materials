CREATE INDEX batches_materials_idx ON material_batches(materials_id);
CREATE INDEX documents_warehouses_idx ON inventory_documents(warehouses_id);
CREATE INDEX documents_suppliers_idx ON inventory_documents(suppliers_id);
CREATE INDEX documents_departments_idx ON inventory_documents(departments_id);
CREATE INDEX documents_users_idx ON inventory_documents(users_id);
CREATE INDEX items_documents_idx ON inventory_document_items(inventory_documents_id);
CREATE INDEX items_batches_idx ON inventory_document_items(material_batches_id);

