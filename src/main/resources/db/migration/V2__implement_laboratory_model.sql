CREATE TABLE units (
    id_units BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    symbol VARCHAR(32) NOT NULL
);
CREATE TABLE categories (
    id_categories BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);
CREATE TABLE departments (
    id_departments BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departments_id BIGINT REFERENCES departments(id_departments),
    name VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT departments_no_self_parent CHECK (departments_id IS NULL OR departments_id <> id_departments)
);
CREATE TABLE warehouses (
    id_warehouses BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE suppliers (
    id_suppliers BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    inn VARCHAR(12),
    contact_info VARCHAR(1000),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE users (
    id_users BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departments_id BIGINT REFERENCES departments(id_departments),
    login VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    role VARCHAR(32) NOT NULL CHECK (role IN ('ADMIN', 'STOREKEEPER', 'RECIPIENT')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

