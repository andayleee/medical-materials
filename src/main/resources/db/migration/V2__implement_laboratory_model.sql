CREATE TABLE material_batches (
    id_material_batches BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    materials_id BIGINT NOT NULL REFERENCES materials(id_materials),
    batch_number VARCHAR(100) NOT NULL,
    expires_on DATE,
    purchase_unit_price NUMERIC(19,4) CHECK (purchase_unit_price >= 0)
);
CREATE TABLE inventory_documents (
    id_inventory_documents BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouses_id BIGINT NOT NULL REFERENCES warehouses(id_warehouses),
    suppliers_id BIGINT REFERENCES suppliers(id_suppliers),
    departments_id BIGINT REFERENCES departments(id_departments),
    users_id BIGINT NOT NULL REFERENCES users(id_users),
    number VARCHAR(64) NOT NULL,
    type VARCHAR(32) NOT NULL CHECK (type IN ('RECEIPT', 'ISSUE', 'WRITE_OFF')),
    status VARCHAR(32) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'POSTED')),
    document_date DATE NOT NULL,
    posted_at TIMESTAMPTZ,
    write_off_reason VARCHAR(1000),
    CONSTRAINT documents_parties CHECK (
        (type = 'RECEIPT' AND suppliers_id IS NOT NULL AND departments_id IS NULL) OR
        (type = 'ISSUE' AND suppliers_id IS NULL AND departments_id IS NOT NULL) OR
        (type = 'WRITE_OFF' AND suppliers_id IS NULL AND departments_id IS NULL
            AND write_off_reason IS NOT NULL AND length(trim(write_off_reason)) > 0)
    ),
    CONSTRAINT documents_posted_at CHECK (
        (status = 'DRAFT' AND posted_at IS NULL) OR
        (status = 'POSTED' AND posted_at IS NOT NULL)
    )
);
CREATE TABLE inventory_document_items (
    id_inventory_document_items BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_documents_id BIGINT NOT NULL REFERENCES inventory_documents(id_inventory_documents),
    material_batches_id BIGINT NOT NULL REFERENCES material_batches(id_material_batches),
    line_number INTEGER NOT NULL CHECK (line_number > 0),
    quantity NUMERIC(19,4) NOT NULL CHECK (quantity > 0)
);

